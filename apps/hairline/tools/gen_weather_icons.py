#!/usr/bin/env python3
"""Generate Hairline's line-art weather icons as Android VectorDrawables.

Run it after editing any geometry below:

    python3 tools/gen_weather_icons.py

It writes the VectorDrawables the widget uses, plus SVG copies under build/icon-preview/
so the set can be eyeballed in a browser without building the app.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "app/src/main/res/drawable")
PREVIEW = os.path.join(ROOT, "build/icon-preview")

SUN = "#FFB300"
MOON = "#E8EAF0"
CLOUD = "#4FC3F7"
RAIN = "#4FC3F7"
SNOW = "#B3E5FC"
FOG = "#90A4AE"
BOLT = "#FFB300"

SW = "1.7"

# ---- shared geometry ---------------------------------------------------------
def cloud(dy=0.0, scale=1.0, dx=0.0):
    """Closed cloud outline: left bump, top bump, right bump, flat base."""
    pts = [(5.2, 18.0), (8.9, 13.6), (16.6, 13.9), (19.8, 18.0)]
    r = [3.0, 4.2, 2.8]
    def t(p):
        return (round(12 + (p[0] - 12) * scale + dx, 2), round(12 + (p[1] - 12) * scale + dy, 2))
    a, b, c, d = [t(p) for p in pts]
    rr = [round(x * scale, 2) for x in r]
    return (f"M{a[0]},{a[1]} A{rr[0]},{rr[0]} 0 0,1 {b[0]},{b[1]} "
            f"A{rr[1]},{rr[1]} 0 0,1 {c[0]},{c[1]} "
            f"A{rr[2]},{rr[2]} 0 0,1 {d[0]},{d[1]} Z")

def sun(cx=12.0, cy=12.0, r=5.0, ray_in=7.0, ray_out=9.6, rays=8, skip=()):
    import math
    paths = [f"M{round(cx-r,2)},{cy} A{r},{r} 0 1,1 {round(cx+r,2)},{cy} "
             f"A{r},{r} 0 1,1 {round(cx-r,2)},{cy}"]
    for i in range(rays):
        if i in skip:
            continue
        ang = math.radians(i * (360.0 / rays))
        x1, y1 = cx + ray_in * math.cos(ang), cy + ray_in * math.sin(ang)
        x2, y2 = cx + ray_out * math.cos(ang), cy + ray_out * math.sin(ang)
        paths.append(f"M{round(x1,2)},{round(y1,2)} L{round(x2,2)},{round(y2,2)}")
    return paths

def slant(x, y, dx=-1.1, dy=3.0):
    return f"M{x},{y} L{round(x+dx,2)},{round(y+dy,2)}"

def flake(x, y, r=1.9):
    import math
    out = []
    for i in range(3):
        ang = math.radians(i * 60)
        out.append(f"M{round(x-r*math.cos(ang),2)},{round(y-r*math.sin(ang),2)} "
                   f"L{round(x+r*math.cos(ang),2)},{round(y+r*math.sin(ang),2)}")
    return out

def drop(x, y):
    return f"M{x},{y} L{x},{round(y+2.2,2)}"

# ---- icons -------------------------------------------------------------------
CLOUD_HIGH = cloud(dy=-3.4)

ICONS = {
    "wx_clear_day": [(SUN, p) for p in sun()],

    "wx_clear_night": [(MOON,
        "M19.6,14.9 A8.4,8.4 0 1,1 9.1,4.4 A7,7 0 0,0 19.6,14.9 Z")],

    "wx_partly_day": [(SUN, p) for p in sun(cx=8.6, cy=8.2, r=3.1, ray_in=4.8, ray_out=6.6,
                                            rays=8, skip=(0, 1, 2))] +
                     [(CLOUD, cloud(dy=0.4, scale=0.82, dx=1.6))],

    "wx_partly_night": [(MOON,
        "M13.6,10.4 A5.4,5.4 0 1,1 7,3.8 A4.5,4.5 0 0,0 13.6,10.4 Z")] +
        [(CLOUD, cloud(dy=0.4, scale=0.82, dx=1.6))],

    "wx_cloudy": [(CLOUD, cloud(dy=-1.6, scale=1.06))],

    "wx_fog": [(CLOUD, CLOUD_HIGH)] + [
        (FOG, "M5.6,17.4 L18.4,17.4"),
        (FOG, "M7.4,20.4 L20.2,20.4"),
    ],

    "wx_drizzle": [(CLOUD, CLOUD_HIGH)] + [
        (RAIN, drop(9.0, 16.6)), (RAIN, drop(12.5, 17.6)), (RAIN, drop(16.0, 16.6)),
    ],

    "wx_rain": [(CLOUD, CLOUD_HIGH)] + [
        (RAIN, slant(9.6, 16.4)), (RAIN, slant(13.2, 16.4)), (RAIN, slant(16.8, 16.4)),
    ],

    "wx_rain_heavy": [(CLOUD, CLOUD_HIGH)] + [
        (RAIN, slant(8.4, 16.2, dy=3.4)), (RAIN, slant(11.2, 16.2, dy=3.4)),
        (RAIN, slant(14.0, 16.2, dy=3.4)), (RAIN, slant(16.8, 16.2, dy=3.4)),
    ],

    "wx_snow": [(CLOUD, CLOUD_HIGH)] + [(SNOW, p, "1.1") for p in
        flake(8.9, 17.9) + flake(15.1, 17.9) + flake(12.0, 21.0, r=1.6)],

    "wx_sleet": [(CLOUD, CLOUD_HIGH)] + [(RAIN, slant(9.6, 16.4))] +
        [(SNOW, p, "1.1") for p in flake(15.4, 18.4)],

    "wx_thunder": [(CLOUD, CLOUD_HIGH)] + [
        (BOLT, "M14.0,15.2 L9.9,19.6 L12.9,19.6 L11.2,22.8"),
    ],
}

VD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_weather_icons.py — edit the generator, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
{paths}
</vector>
"""

PATH = """    <path
        android:pathData="{d}"
        android:fillColor="#00000000"
        android:strokeColor="{c}"
        android:strokeWidth="{w}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />"""


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(PREVIEW, exist_ok=True)
    for name, paths in ICONS.items():
        paths = [(p[0], p[1], p[2] if len(p) > 2 else SW) for p in paths]
        body = "\n".join(PATH.format(d=d, c=c, w=w) for c, d, w in paths)
        with open(os.path.join(OUT, name + ".xml"), "w") as f:
            f.write(VD.format(paths=body))
        svg = ['<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 24 24">',
               '<rect width="24" height="24" fill="#0b0d12"/>']
        for c, d, w in paths:
            svg.append(f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" '
                       'stroke-linecap="round" stroke-linejoin="round"/>')
        svg.append("</svg>")
        with open(os.path.join(PREVIEW, name + ".svg"), "w") as f:
            f.write("\n".join(svg))
    print(f"wrote {len(ICONS)} drawables to {OUT}")


if __name__ == "__main__":
    main()
